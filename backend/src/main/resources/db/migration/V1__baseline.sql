-- Baseline: the schema Hibernate generated before Flyway was introduced.
-- Databases that already have these tables are baselined at version 1
-- (spring.flyway.baseline-on-migrate), so this file only runs on empty ones.
-- Kept to SQL that both PostgreSQL and H2 (PostgreSQL mode, used by tests) accept.

CREATE TABLE organizations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name       VARCHAR(255) NOT NULL,
    slug       VARCHAR(255) NOT NULL,
    CONSTRAINT uk_organizations_name UNIQUE (name),
    CONSTRAINT uk_organizations_slug UNIQUE (slug)
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email           VARCHAR(255) NOT NULL,
    full_name       VARCHAR(255) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    role            VARCHAR(255) NOT NULL,
    organization_id BIGINT NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('OWNER', 'ADMIN', 'FARMER', 'BUYER')),
    CONSTRAINT fk_users_organization FOREIGN KEY (organization_id) REFERENCES organizations (id)
);

CREATE TABLE farms (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id     BIGINT NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    location      VARCHAR(255) NOT NULL,
    name          VARCHAR(255) NOT NULL,
    size_hectares DOUBLE PRECISION
);

CREATE TABLE crops (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id             BIGINT NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    crop_name             VARCHAR(255) NOT NULL,
    expected_harvest_date DATE,
    planting_date         DATE,
    status                VARCHAR(255) NOT NULL,
    farm_id               BIGINT NOT NULL,
    CONSTRAINT crops_status_check CHECK (status IN ('PLANTED', 'GROWING', 'HARVESTED', 'FAILED')),
    CONSTRAINT fk_crops_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE TABLE livestock (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id    BIGINT NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    breed        VARCHAR(255),
    health_notes VARCHAR(255),
    quantity     INTEGER NOT NULL,
    species      VARCHAR(255) NOT NULL,
    farm_id      BIGINT NOT NULL,
    CONSTRAINT fk_livestock_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE TABLE expenses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id   BIGINT NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    amount      NUMERIC(12, 2) NOT NULL,
    category    VARCHAR(255) NOT NULL,
    date        DATE NOT NULL,
    description VARCHAR(255),
    farm_id     BIGINT NOT NULL,
    CONSTRAINT fk_expenses_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE TABLE revenues (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id  BIGINT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    amount     NUMERIC(12, 2) NOT NULL,
    date       DATE NOT NULL,
    source     VARCHAR(255) NOT NULL,
    farm_id    BIGINT NOT NULL,
    CONSTRAINT fk_revenues_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE TABLE inventory_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id   BIGINT NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    category    VARCHAR(255) NOT NULL,
    item_name   VARCHAR(255) NOT NULL,
    quantity_kg DOUBLE PRECISION NOT NULL,
    farm_id     BIGINT NOT NULL,
    CONSTRAINT fk_inventory_items_farm FOREIGN KEY (farm_id) REFERENCES farms (id)
);

CREATE TABLE yield_records (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tenant_id    BIGINT NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    harvest_date DATE NOT NULL,
    quantity_kg  DOUBLE PRECISION NOT NULL,
    crop_id      BIGINT NOT NULL,
    CONSTRAINT fk_yield_records_crop FOREIGN KEY (crop_id) REFERENCES crops (id)
);

CREATE TABLE listings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    description        VARCHAR(255),
    farm_id            BIGINT,
    organization_id    BIGINT NOT NULL,
    price_per_unit     NUMERIC(12, 2) NOT NULL,
    produce_name       VARCHAR(255) NOT NULL,
    quantity_available NUMERIC(12, 2) NOT NULL,
    status             VARCHAR(255) NOT NULL,
    unit               VARCHAR(255) NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT listings_status_check CHECK (status IN ('ACTIVE', 'SOLD_OUT', 'CLOSED'))
);

CREATE TABLE orders (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_organization_id  BIGINT NOT NULL,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    listing_id             BIGINT NOT NULL,
    quantity               NUMERIC(12, 2) NOT NULL,
    seller_organization_id BIGINT NOT NULL,
    status                 VARCHAR(255) NOT NULL,
    total_amount           NUMERIC(12, 2) NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT orders_status_check CHECK (status IN ('PENDING_PAYMENT', 'PAID', 'FULFILLED', 'CANCELLED'))
);

CREATE TABLE escrow_transactions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount                NUMERIC(12, 2) NOT NULL,
    buyer_organization_id BIGINT NOT NULL,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    order_id              BIGINT NOT NULL,
    paystack_reference    VARCHAR(255) NOT NULL,
    status                VARCHAR(255) NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_escrow_transactions_reference UNIQUE (paystack_reference),
    CONSTRAINT escrow_transactions_status_check CHECK (status IN ('PENDING', 'HELD', 'RELEASED', 'REFUNDED', 'FAILED'))
);
